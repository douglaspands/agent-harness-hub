"""Avaliação de eficiência do ctx sob demanda (`ctx evaluate`): está compensando ou é esforço à toa?

Responde, com números e SUPOSIÇÕES explícitas, se o ctx está economizando chamadas e tokens (principalmente com modelos
menos eficientes) ou se custa mais do que devolve. Fontes: transcripts do agente + `.ctx/events.jsonl` + o tamanho real
das instruções que o ctx injeta em toda sessão.

Princípios:
- tokens são ESTIMATIVAS (caracteres / 4) e as economias dependem de suposições configuráveis
  (`[metrics.evaluate]`: tokens_per_call, recall_hit_calls, ...), sempre listadas no relatório;
- o custo fixo (bloco de instruções) e o desperdício (bloqueios do guardrail) são subtraídos do ganho: o saldo líquido
  por sessão é o número que decide;
- amostra pequena => "sem dados" (nunca conclui sem evidência); recurso nunca usado em muitas sessões => "não compensa";
- a comparação com/sem ctx por modelo é indício, não prova (tarefas diferentes pesam diferente) e o relatório avisa.

100% biblioteca padrão.
"""

from __future__ import annotations

import re
import statistics
import time
from pathlib import Path
from typing import Any

from ctx.config import load_config
from ctx.memory_db import memory_path
from ctx.metrics import analyze, event_summary, transcripts_dir_for

COMPENSA, MARGINAL, NAO, SEM_DADOS = "compensa", "marginal", "não compensa", "sem dados"
CTX_USAGE = ("ctx_search", "ctx_map", "ctx_status", "ctx_recall", "ctx_fact", "ctx_upstream", "ctx_recipe")
BLOCK_RE = re.compile(r"<!-- AUTOGENERATED_BY_CTX_START -->.*?<!-- AUTOGENERATED_BY_CTX_END -->", re.DOTALL)
SKILL_DESC_RE = re.compile(r"^description:\s*(.+)$", re.MULTILINE)


def est_tokens(chars: int) -> int:
    return round(chars / 4)


def parse_window(value: str | None) -> float:
    if not value:
        return 0.0
    m = re.fullmatch(r"(\d+)([hdw])", value.strip().lower())
    if not m:
        raise ValueError(f"--since inválido: {value!r} (ex.: 12h, 30d, 4w)")
    return time.time() - int(m.group(1)) * {"h": 3600, "d": 86400, "w": 604800}[m.group(2)]


def instruction_overhead(workspace_root: Path) -> dict[str, Any]:
    """Custo fixo por sessão: bloco de instruções gerado (AGENTS/CLAUDE/GEMINI.md) + descrição da skill, em tokens."""
    per_file: dict[str, int] = {}
    for name in ("CLAUDE.md", "AGENTS.md", "GEMINI.md"):
        p = workspace_root / name
        if p.is_file():
            m = BLOCK_RE.search(p.read_text(encoding="utf-8", errors="replace"))
            if m:
                per_file[name] = est_tokens(len(m.group(0)))
    skill_tokens = 0
    skill = workspace_root / ".claude" / "skills" / "workspace-ctx" / "SKILL.md"
    if skill.is_file():
        m = SKILL_DESC_RE.search(skill.read_text(encoding="utf-8", errors="replace"))
        skill_tokens = est_tokens(len(m.group(1))) if m else 0
    block = max(per_file.values(), default=0)
    return {"block_tokens": block, "skill_description_tokens": skill_tokens, "per_session": block + skill_tokens, "per_file": per_file}


def fact_counts(workspace_root: Path) -> dict[str, int]:
    if not memory_path(workspace_root).exists():
        return {"total": 0, "stale": 0}
    from ctx.facts import stale_facts

    res = stale_facts(workspace_root)
    return {"total": len(res["stale"]) + len(res["ok"]) + len(res["unverifiable"]), "stale": len(res["stale"])}


def verdict_feature(name: str, verdict: str, evidence: str, saved_calls: int = 0) -> dict[str, Any]:
    return {"feature": name, "verdict": verdict, "evidence": evidence, "saved_calls": saved_calls}


def uses_ctx(s: dict[str, Any]) -> bool:
    return any(s[k] for k in CTX_USAGE)


def evaluate_features(data: dict[str, Any], sessions: list[dict[str, Any]], cfg: dict[str, Any], facts: dict[str, int]) -> list[dict[str, Any]]:
    t, ev = data["totals"], data.get("events", {})
    n = len(sessions)
    ctx_n = sum(1 for s in sessions if uses_ctx(s))
    enough = n >= cfg["min_sessions"]
    adopted = ctx_n >= cfg["min_sessions"]  # só dá para dizer "não é usado" se o ctx é usado em outras coisas
    out: list[dict[str, Any]] = []

    # 1. Busca e índice
    uses, detours = t["ctx_search"], t["rg_detours"]
    saved = max(0, t["ctx_queries"] - t["ctx_search"])
    lat = ev.get("latency", {}).get("search")
    lat_note = f"; p95 {lat['p95_ms']}ms" if lat else ""
    if not enough or uses + detours == 0:
        out.append(verdict_feature("busca e índice", SEM_DADOS, f"{n} sessões; {uses} buscas ctx, {detours} rg/grep/sed{lat_note}"))
    else:
        adoption = uses / (uses + detours)
        v = COMPENSA if adoption >= cfg["search_adoption_ok"] else MARGINAL if adoption >= 0.2 else NAO
        # por sessão separa "não usa" de "usa pouco" (M-22)
        search_n = sum(1 for s in sessions if s["ctx_search"])
        out.append(verdict_feature(
            "busca e índice", v,
            f"{uses} buscas ctx vs {detours} desvios rg/grep/sed (adoção {adoption:.0%} por chamada; {search_n}/{n} sessões "
            f"usaram `ctx search`, {ctx_n}/{n} algum comando do ctx); {saved} chamadas poupadas por multi-query{lat_note}",
            saved,
        ))

    # 2. Recall
    q, hits = ev.get("recall_queries", 0), ev.get("recall_hits", 0)
    if not adopted and q == 0:
        out.append(verdict_feature("recall (transcripts)", SEM_DADOS, f"ctx usado em {ctx_n}/{n} sessões; sem consultas de recall"))
    elif q == 0:
        out.append(verdict_feature("recall (transcripts)", NAO, f"nunca consultado em {n} sessões (ctx usado em {ctx_n})"))
    else:
        rate = hits / q
        v = COMPENSA if q >= 3 and rate >= 0.5 else MARGINAL if rate >= 0.2 else NAO
        out.append(verdict_feature(
            "recall (transcripts)", v if q >= 3 or v == NAO else MARGINAL,
            f"{q} consultas, {hits} com resultado ({rate:.0%})", hits * cfg["recall_hit_calls"],
        ))

    # 3. Fatos
    fs, fh = ev.get("fact_searches", 0), ev.get("fact_hits", 0)
    if facts["total"] == 0 and fs == 0:
        out.append(verdict_feature("fatos verificados", SEM_DADOS, "nenhum fato registrado (use `ctx fact add` / `ctx fact review`)"))
    elif fs == 0:
        out.append(verdict_feature("fatos verificados", NAO, f"{facts['total']} fatos registrados, nunca consultados"))
    else:
        stale_ratio = facts["stale"] / facts["total"] if facts["total"] else 0
        v = COMPENSA if fh >= 3 and stale_ratio < 0.3 else MARGINAL
        out.append(verdict_feature(
            "fatos verificados", v,
            f"{facts['total']} fatos ({facts['stale']} com fonte alterada), {fs} consultas, {fh} com resultado", fh * cfg["recall_hit_calls"],
        ))

    # 4. Upstream em cache
    gets, cached, redl = ev.get("upstream_gets", 0), ev.get("upstream_cached", 0), t["redownloads"]
    if gets == 0 and redl == 0:
        out.append(verdict_feature("upstream em cache", SEM_DADOS, "sem downloads de fonte upstream nas sessões"))
    elif gets == 0:
        out.append(verdict_feature("upstream em cache", NAO, f"{redl} re-downloads manuais da mesma URL e recurso não usado (declare [upstream.*])"))
    else:
        out.append(verdict_feature(
            "upstream em cache", COMPENSA if cached >= 1 else MARGINAL,
            f"{gets} chamadas, {cached} servidas do cache sem rede; {redl} re-downloads manuais restantes", cached,
        ))

    # 5. Receitas
    runs, ok, steps_saved, hints = ev.get("recipe_runs", 0), ev.get("recipe_ok", 0), ev.get("recipe_steps_saved", 0), ev.get("hints", 0)
    if runs == 0 and hints == 0:
        out.append(verdict_feature("receitas", SEM_DADOS, "nenhuma receita executada e nenhuma sequência manual detectada"))
    elif runs == 0:
        out.append(verdict_feature("receitas", NAO, f"{hints} sequências manuais detectadas pelo guardrail, nenhuma receita executada"))
    else:
        v = COMPENSA if steps_saved >= 5 else MARGINAL if steps_saved >= 1 else NAO
        out.append(verdict_feature(
            "receitas", v, f"{runs} execuções ({ok} ok), {steps_saved} chamadas economizadas, {hints} dicas emitidas", steps_saved,
        ))

    # 6. Coaching do guardrail (aprendizado: bloqueios devem diminuir ao longo das sessões)
    ordered = sorted(sessions, key=lambda s: s["started"])
    total_den = t["denials"]
    if not enough or total_den == 0:
        out.append(verdict_feature("coaching do guardrail", SEM_DADOS, f"{total_den} bloqueios em {n} sessões"))
    else:
        half = len(ordered) // 2
        first = statistics.mean(s["denials"] for s in ordered[:half])
        second = statistics.mean(s["denials"] for s in ordered[half:])
        v = COMPENSA if second <= first * 0.8 else NAO if second >= max(1.0, first * 1.2) else MARGINAL
        out.append(verdict_feature(
            "coaching do guardrail", v, f"{total_den} bloqueios; média por sessão {first:.1f} → {second:.1f} (1ª → 2ª metade)",
        ))
    return out


def by_model(sessions: list[dict[str, Any]], cfg: dict[str, Any]) -> list[dict[str, Any]]:
    groups: dict[str, list[dict[str, Any]]] = {}
    for s in sessions:
        groups.setdefault(s["model"] or "desconhecido", []).append(s)
    out = []
    for model, ss in sorted(groups.items()):
        with_ctx = [s for s in ss if uses_ctx(s)]
        without = [s for s in ss if not uses_ctx(s)]

        def avg(group: list[dict[str, Any]], key: str) -> float | None:
            return round(statistics.mean(s[key] for s in group), 1) if group else None

        row: dict[str, Any] = {
            "model": model, "sessions": len(ss), "with_ctx": len(with_ctx), "without_ctx": len(without),
            "adoption": round(len(with_ctx) / len(ss), 2),
            "avg_calls_with": avg(with_ctx, "calls"), "avg_calls_without": avg(without, "calls"),
            "avg_result_tokens_with": est_tokens(int(avg(with_ctx, "result_chars") or 0)) if with_ctx else None,
            "avg_result_tokens_without": est_tokens(int(avg(without, "result_chars") or 0)) if without else None,
            "avg_waste_with": round(statistics.mean(s["repeated_cmds"] + s["redownloads"] for s in with_ctx), 1) if with_ctx else None,
            "avg_waste_without": round(statistics.mean(s["repeated_cmds"] + s["redownloads"] for s in without), 1) if without else None,
        }
        mg = cfg["min_group_sessions"]
        if len(with_ctx) >= mg and len(without) >= mg and row["avg_calls_without"]:
            row["calls_delta_pct"] = round(100 * (row["avg_calls_with"] - row["avg_calls_without"]) / row["avg_calls_without"], 1)
            row["comparison"] = "ok"
        else:
            row["comparison"] = f"amostra pequena (com ctx {len(with_ctx)}, sem ctx {len(without)}; mínimo {mg} em cada)"
        out.append(row)
    return out


def recommendations(features: list[dict[str, Any]], overall: dict[str, Any], n: int, cfg: dict[str, Any]) -> list[str]:
    by = {f["feature"]: f for f in features}
    recs: list[str] = []
    if overall["verdict"] == SEM_DADOS:
        recs.append(f"Amostra insuficiente ({n} sessões; mínimo {cfg['min_sessions']}): use por mais algumas sessões antes de decidir.")
    if overall["overhead_tokens_per_session"] > overall["saved_tokens_per_session"] > 0 or overall["verdict"] == NAO:
        recs.append(
            f"O custo fixo (~{overall['overhead_tokens_per_session']} tokens de instruções por sessão) supera o ganho estimado: "
            "enxugue o bloco gerado (desabilite harnesses que não usa em [harnesses].enabled) ou mantenha só os recursos que aparecem como 'compensa'."
        )
    if by["busca e índice"]["verdict"] == NAO:
        recs.append("O agente prefere rg/grep/sed ao `ctx search`: ative `[file_tools] mode = \"coach\"` e reforce a seção 1 do AGENTS.md; se não pegar, o índice não vale o custo neste projeto.")
    if by["recall (transcripts)"]["verdict"] == NAO:
        recs.append("Recall nunca consultado: lembre o agente de rodar `ctx recall` ao retomar sessões (instrução no AGENTS.md) ou desligue o recurso.")
    if by["fatos verificados"]["verdict"] == NAO:
        recs.append("Há fatos que nunca são consultados: remova os obsoletos (`ctx fact stale`) e peça `ctx fact search` antes de redescobrir valores.")
    if by["upstream em cache"]["verdict"] == NAO:
        recs.append("Há re-downloads manuais: declare o projeto em `[upstream.<nome>]` do policy.toml para passar a usar `ctx upstream get`.")
    if by["fatos verificados"]["verdict"] == SEM_DADOS and n >= cfg["min_sessions"]:
        recs.append(
            "Nenhum fato registrado: o que custou caro descobrir deve entrar com "
            "`ctx fact add \"<fato>\" --source arquivo:linha --tags a,b` (ex.: um valor medido, a causa de um bug, a URL "
            "de um patch, o comando de build que funcionou), para o `recall` não depender só do transcript."
        )
    if overall.get("confidence") == "provisório" and overall["verdict"] != SEM_DADOS:
        recs.append(
            f"Veredito provisório: {n} sessões (confiança a partir de {cfg['confident_sessions']}); repita o "
            "`ctx evaluate` depois de mais sessões antes de desligar um recurso."
        )
    top = overall.get("denial_rules", [])[:1]
    if top and overall.get("denial_repeats", 0) and top[0]["count"] > 1:
        recs.append(
            f"A regra `{top[0]['rule']}` é o bloqueio mais caro ({top[0]['count']}x, ~{top[0]['tokens']} tokens) e "
            f"{overall['denial_repeats']} bloqueios se repetiram na mesma sessão: o agente não aprendeu com a mensagem."
        )
    if by["receitas"]["verdict"] == NAO:
        recs.append("Receitas ignoradas ou sem ganho: use `ctx recipe list`, ajuste as etapas no policy.toml ou remova as que ninguém usa.")
    if by["coaching do guardrail"]["verdict"] == NAO:
        recs.append("Os bloqueios do guardrail não estão diminuindo: o agente não aprende com o coaching; revise as mensagens de `[commands.inefficient_variants]`.")
    if not recs:
        recs.append("Manter como está: nenhum recurso apresenta sinal de desperdício nos dados atuais.")
    return recs


def evaluate(
    workspace_root: Path,
    transcripts_dir: Path | None = None,
    since: str | None = None,
    model: str | None = None,
) -> dict[str, Any]:
    cfg = load_config(workspace_root)["metrics"]["evaluate"]
    tdir = transcripts_dir or transcripts_dir_for(workspace_root)
    since_ts = parse_window(since)
    data = analyze(tdir, workspace_root, since_ts) if tdir.is_dir() else {"sessions": [], "totals": {}, "events": {}}
    sessions = [s for s in data["sessions"] if not model or model.lower() in (s["model"] or "").lower()]
    if not data["sessions"]:
        data["totals"] = {k: 0 for k in ("ctx_search", "ctx_queries", "rg_detours", "redownloads", "denials")}
    else:
        data["totals"] = {k: sum(s[k] for s in sessions) for k in data["totals"] if isinstance(data["totals"][k], int)}
        # eventos do ctx somente das sessões consideradas (o filtro por modelo também vale para eles)
        data["events"] = event_summary([e for s in sessions for e in s.get("events", [])])
    n = len(sessions)
    facts = fact_counts(workspace_root)
    features = evaluate_features(data, sessions, cfg, facts)
    overhead = instruction_overhead(workspace_root)

    saved_calls = sum(f["saved_calls"] for f in features)
    denials = data["totals"].get("denials", 0)
    saved_tokens = saved_calls * cfg["tokens_per_call"]
    cost_tokens = overhead["per_session"] * n + denials * cfg["tokens_per_call"]
    net = saved_tokens - cost_tokens
    net_per_session = round(net / n) if n else 0
    if n < cfg["min_sessions"]:
        verdict = SEM_DADOS
    elif net_per_session >= cfg["min_net_saving_tokens"]:
        verdict = COMPENSA
    elif net_per_session >= 0:
        verdict = MARGINAL
    else:
        verdict = NAO
    # o veredito leva a confiança: abaixo de `confident_sessions` é só provisório (M-20)
    confidence = "ok" if n >= cfg["confident_sessions"] else "provisório"
    # custo dos bloqueios por regra; repetidos na mesma sessão = coaching que não ensinou (M-19)
    rules: dict[str, int] = {}
    for s in sessions:
        for rule, count in s.get("denial_rules", {}).items():
            rules[rule] = rules.get(rule, 0) + count
    denial_rules = [
        {"rule": r, "count": c, "tokens": c * cfg["tokens_per_call"]} for r, c in sorted(rules.items(), key=lambda kv: (-kv[1], kv[0]))
    ]
    overall = {
        "verdict": verdict, "confidence": confidence, "sessions": n,
        "denial_rules": denial_rules, "denial_repeats": sum(s.get("denial_repeats", 0) for s in sessions),
        "saved_calls": saved_calls, "saved_tokens": saved_tokens,
        "saved_tokens_per_session": round(saved_tokens / n) if n else 0,
        "overhead_tokens_per_session": overhead["per_session"],
        "denial_waste_tokens": denials * cfg["tokens_per_call"],
        "cost_tokens": cost_tokens, "net_tokens": net, "net_tokens_per_session": net_per_session,
    }
    return {
        "window": since or "tudo", "model_filter": model, "overall": overall, "features": features,
        "overhead": overhead, "models": by_model(sessions, cfg),
        "recommendations": recommendations(features, overall, n, cfg),
        "assumptions": {
            "tokens são estimativas (caracteres / 4)": True,
            "tokens_per_call": cfg["tokens_per_call"], "recall_hit_calls": cfg["recall_hit_calls"],
            "min_sessions": cfg["min_sessions"], "min_net_saving_tokens": cfg["min_net_saving_tokens"],
            "comparação com/sem ctx por modelo é indício, não prova (tarefas diferentes pesam diferente)": True,
        },
        "transcripts_dir": str(tdir),
    }
