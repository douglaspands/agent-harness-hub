"""Catálogo e instalação de prompts individuais do hub em qualquer projeto (`ctx prompt`).

Cada prompt em prompts/<categoria>/<nome>.md tem:
- frontmatter (title, summary, harnesses, covered_by_kit);
- a seção "## Snippet ..." com um bloco ```markdown``` — o único trecho instalado no projeto.

A instalação insere o snippet em AGENTS.md / CLAUDE.md / GEMINI.md entre marcadores próprios,
de forma idempotente (reinstalar substitui o bloco; remover apaga só o bloco).

100% biblioteca padrão (json, re, urllib, pathlib).
"""

from __future__ import annotations

import json
import re
import urllib.request
from pathlib import Path
from typing import Any

from ctx import __version__

PROMPTS_DIR = "prompts"
CATALOG_PATH = "prompts/catalog.json"
DEFAULT_SOURCE = f"https://raw.githubusercontent.com/douglaspands/agent-harness-hub/v{__version__}/"
INSTRUCTION_FILES = ("AGENTS.md", "CLAUDE.md", "GEMINI.md")
KIT_MARKER = "<!-- AUTOGENERATED_BY_CTX_START -->"
NON_PROMPT_FILES = {"INSTALL.md", "README.md"}
FETCH_TIMEOUT_S = 15


def marker_start(prompt_id: str, version: str = "") -> str:
    suffix = f" v{version}" if version else ""
    return f"<!-- agent-harness-hub:prompt {prompt_id}{suffix} START -->"


def marker_end(prompt_id: str) -> str:
    return f"<!-- agent-harness-hub:prompt {prompt_id} END -->"


# --------------------------------------------------------------------------------------
# Parsing
# --------------------------------------------------------------------------------------


def _parse_value(raw: str) -> Any:
    raw = raw.strip()
    if raw in ("true", "false"):
        return raw == "true"
    if raw.startswith("[") and raw.endswith("]"):
        return [item.strip().strip("\"'") for item in raw[1:-1].split(",") if item.strip()]
    return raw.strip("\"'")


def parse_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    """Lê um frontmatter simples (chave: valor, listas [a, b], true/false). Sem dependências de YAML."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}, text
    meta: dict[str, Any] = {}
    for line in text[4:end].splitlines():
        if ":" in line and not line.lstrip().startswith("#"):
            key, value = line.split(":", 1)
            meta[key.strip()] = _parse_value(value)
    return meta, text[end + 5 :]


def extract_snippet(body: str) -> str:
    """Retorna o conteúdo do 1º bloco cercado (```) após o título '## Snippet'."""
    lines = body.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.startswith("## Snippet"))
    except StopIteration as exc:
        raise ValueError("seção '## Snippet' não encontrada") from exc
    fence_open = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("```")), None)
    if fence_open is None:
        raise ValueError("bloco ``` não encontrado na seção '## Snippet'")
    fence_close = next((i for i in range(fence_open + 1, len(lines)) if lines[i].strip() == "```"), None)
    if fence_close is None:
        raise ValueError("bloco ``` da seção '## Snippet' não foi fechado")
    snippet = "\n".join(lines[fence_open + 1 : fence_close]).strip()
    if not snippet:
        raise ValueError("snippet vazio")
    return snippet


def prompt_id_for(path: Path, prompts_root: Path) -> str:
    return path.relative_to(prompts_root).with_suffix("").as_posix()


def load_prompt(text: str, prompt_id: str) -> dict[str, Any]:
    meta, body = parse_frontmatter(text)
    for field in ("title", "summary"):
        if not meta.get(field):
            raise ValueError(f"{prompt_id}: frontmatter sem '{field}'")
    return {
        "id": prompt_id,
        "title": meta["title"],
        "summary": meta["summary"],
        "category": prompt_id.split("/")[0],
        "harnesses": meta.get("harnesses", []),
        "covered_by_kit": bool(meta.get("covered_by_kit", False)),
        "requires": meta.get("requires", []),
        "path": f"{PROMPTS_DIR}/{prompt_id}.md",
        "snippet": extract_snippet(body),
    }


# --------------------------------------------------------------------------------------
# Catálogo (gerado no hub)
# --------------------------------------------------------------------------------------


def build_catalog(repo_root: Path) -> dict[str, Any]:
    prompts_root = repo_root / PROMPTS_DIR
    entries = []
    for path in sorted(prompts_root.rglob("*.md")):
        if path.parent == prompts_root and path.name in NON_PROMPT_FILES:
            continue
        prompt = load_prompt(path.read_text(encoding="utf-8"), prompt_id_for(path, prompts_root))
        prompt.pop("snippet")
        entries.append(prompt)
    return {"version": __version__, "prompts": entries}


def render_catalog(repo_root: Path) -> str:
    return json.dumps(build_catalog(repo_root), indent=2, ensure_ascii=False) + "\n"


def write_catalog(repo_root: Path) -> Path:
    """Regenera prompts/catalog.json e as seções geradas do README (como aplicar + catálogo)."""
    path = repo_root / CATALOG_PATH
    path.write_text(render_catalog(repo_root), encoding="utf-8")
    readme = repo_root / "README.md"
    if readme.exists():
        readme.write_text(update_readme(readme.read_text(encoding="utf-8"), build_catalog(repo_root)), encoding="utf-8")
    return path


# --------------------------------------------------------------------------------------
# README (seções geradas a partir do catálogo)
# --------------------------------------------------------------------------------------

README_SECTIONS = ("APPLY", "CATALOG")
RAW_BASE = "https://raw.githubusercontent.com/douglaspands/agent-harness-hub"


def _readme_markers(name: str) -> tuple[str, str]:
    return (
        f"<!-- {name}:START — gerado por `ctx prompt catalog`; não edite à mão -->",
        f"<!-- {name}:END -->",
    )


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_readme_apply(version: str) -> str:
    tag = f"v{version}"
    return f"""## 🚀 Como Aplicar um Prompt

1. Escolha o **ID** de um ou mais prompts no [catálogo](#-catálogo-de-prompts).
2. Na pasta do projeto de destino, peça ao seu agente (Claude Code, Antigravity, Codex, Cursor…):

   ```text
   Instale o prompt <ID> do agent-harness-hub seguindo
   {RAW_BASE}/{tag}/prompts/INSTALL.md
   ```

   Para vários prompts, liste os IDs separados por espaço.
3. Reinicie a sessão do agente para ele carregar as instruções novas.

Pelo terminal, em projetos com o kit: `.venv/bin/ctx prompt add <ID> [<ID> ...]` (listar: `ctx prompt list`; remover: `ctx prompt remove <ID>`).

**O que acontece:** só o bloco de snippet do prompt é inserido em `AGENTS.md` / `CLAUDE.md` / `GEMINI.md` (os que existirem; senão é criado o `AGENTS.md`, lido por Codex, Cursor, Copilot e outros), entre marcadores `<!-- agent-harness-hub:prompt <ID> ... -->`. Reinstalar atualiza o bloco; nada fora dele é alterado.

**Por que a URL tem tag (`{tag}`) e não `main`:** o conteúdo fica imutável e auditável; um commit futuro na `main` não muda o que o seu agente obedece.

### Kit completo (bloqueio real, não só instruções)

Além dos prompts, o hub tem um kit com guardrail de pré-execução (bloqueio real no Claude Code, Codex, Cursor e Gemini CLI), `policy.toml`, motor de busca local `ctx` e skills. Ele já inclui os prompts marcados com ✅ na coluna **Kit**, e é pré-requisito dos prompts com `kit` na coluna **Requer**:

```text
Leia {RAW_BASE}/{tag}/BOOTSTRAP.md e siga as instruções
para instalar o kit agent-harness-hub neste projeto. Respeite as regras de confirmação do documento e
me pergunte antes de alterar dependências ou qualquer coisa fora do projeto.
```"""


def render_readme_catalog(catalog: dict[str, Any]) -> str:
    prompts = catalog["prompts"]
    lines = [
        "## 📚 Catálogo de Prompts",
        "",
        f"**{len(prompts)} prompts** · versão `v{catalog['version']}` · catálogo em JSON: [`prompts/catalog.json`](prompts/catalog.json)",
    ]
    by_category: dict[str, list[dict[str, Any]]] = {}
    for p in prompts:
        by_category.setdefault(p["category"], []).append(p)
    for category in sorted(by_category):
        lines += [
            "",
            f"### `{category}`",
            "",
            "| Prompt | ID para aplicar | O que faz | Harnesses | Requer | Kit |",
            "| :--- | :--- | :--- | :--- | :---: | :---: |",
        ]
        for p in sorted(by_category[category], key=lambda x: x["id"]):
            harnesses = ", ".join(p.get("harnesses") or []) or "Todos"
            requires = ", ".join(p.get("requires") or []) or "—"
            kit = "✅" if p["covered_by_kit"] else "—"
            lines.append(
                f"| [**{_cell(p['title'])}**]({p['path']}) | `{p['id']}` | {_cell(p['summary'])} | {_cell(harnesses)} | {requires} | {kit} |"
            )
    return "\n".join(lines)


def update_readme(text: str, catalog: dict[str, Any]) -> str:
    """Substitui o conteúdo entre os marcadores APPLY e CATALOG do README."""
    rendered = {"APPLY": render_readme_apply(catalog["version"]), "CATALOG": render_readme_catalog(catalog)}
    for name in README_SECTIONS:
        start, end = _readme_markers(name)
        pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
        if not pattern.search(text):
            raise ValueError(f"README sem os marcadores da seção {name}: {start} ... {end}")
        text = pattern.sub(lambda _m, n=name: f"{start}\n{rendered[n]}\n{end}", text, count=1)
    return text


# --------------------------------------------------------------------------------------
# Fonte (URL fixada por tag ou diretório local do hub)
# --------------------------------------------------------------------------------------


def read_source(source: str, rel_path: str) -> str:
    if source.startswith("https://"):
        url = source.rstrip("/") + "/" + rel_path
        req = urllib.request.Request(url, headers={"User-Agent": f"agent-harness-hub-ctx/{__version__}"})
        with urllib.request.urlopen(req, timeout=FETCH_TIMEOUT_S) as resp:  # noqa: S310 (somente https)
            return resp.read().decode("utf-8")
    if "://" in source:
        raise ValueError(f"Fonte não suportada (use https:// ou um diretório local): {source}")
    return (Path(source).expanduser() / rel_path).read_text(encoding="utf-8")


def list_prompts(source: str = DEFAULT_SOURCE) -> list[dict[str, Any]]:
    return json.loads(read_source(source, CATALOG_PATH))["prompts"]


# --------------------------------------------------------------------------------------
# Instalação
# --------------------------------------------------------------------------------------


def render_block(prompt: dict[str, Any], version: str) -> str:
    return f"{marker_start(prompt['id'], version)}\n{prompt['snippet']}\n{marker_end(prompt['id'])}"


def _block_regex(prompt_id: str) -> re.Pattern[str]:
    start = re.escape(f"<!-- agent-harness-hub:prompt {prompt_id}") + r"(?: v[^ ]+)? START -->"
    return re.compile(start + r".*?" + re.escape(marker_end(prompt_id)) + r"\n?", re.DOTALL)


def upsert_block(text: str, prompt_id: str, block: str) -> tuple[str, str]:
    pattern = _block_regex(prompt_id)
    if pattern.search(text):
        new_text = pattern.sub(lambda _m: block + "\n", text, count=1)
        return new_text, "inalterado" if new_text == text else "atualizado"
    if not text or text.endswith("\n\n"):
        sep = ""
    elif text.endswith("\n"):
        sep = "\n"
    else:
        sep = "\n\n"
    return f"{text}{sep}{block}\n", "adicionado"


def target_files(workspace_root: Path, files: list[str] | None) -> list[str]:
    if files:
        return files
    existing = [f for f in INSTRUCTION_FILES if (workspace_root / f).exists()]
    return existing or ["AGENTS.md"]


def add_prompts(
    ids: list[str],
    workspace_root: Path,
    source: str = DEFAULT_SOURCE,
    files: list[str] | None = None,
    force: bool = False,
) -> list[dict[str, str]]:
    """Instala os prompts `ids` nos arquivos de instrução do projeto. Retorna o relatório por arquivo."""
    catalog = {p["id"]: p for p in list_prompts(source)}
    version = json.loads(read_source(source, CATALOG_PATH)).get("version", "")
    report: list[dict[str, str]] = []
    targets = target_files(workspace_root, files)

    for prompt_id in ids:
        entry = catalog.get(prompt_id)
        if entry is None:
            report.append({"id": prompt_id, "file": "-", "status": "não encontrado no catálogo"})
            continue
        prompt = load_prompt(read_source(source, entry["path"]), prompt_id)
        block = render_block(prompt, version)
        for rel in targets:
            path = workspace_root / rel
            text = path.read_text(encoding="utf-8") if path.exists() else ""
            has_kit = KIT_MARKER in text
            if prompt["covered_by_kit"] and has_kit and not force:
                report.append({"id": prompt_id, "file": rel, "status": "pulado (já coberto pelo kit; --force instala mesmo assim)"})
                continue
            if "kit" in prompt["requires"] and not has_kit and not force:
                report.append({"id": prompt_id, "file": rel, "status": "pulado (requer o kit: instale pelo BOOTSTRAP.md; --force instala mesmo assim)"})
                continue
            new_text, status = upsert_block(text, prompt_id, block)
            if new_text != text:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(new_text, encoding="utf-8")
            report.append({"id": prompt_id, "file": rel, "status": status})
    return report


def remove_prompts(ids: list[str], workspace_root: Path, files: list[str] | None = None) -> list[dict[str, str]]:
    report: list[dict[str, str]] = []
    for prompt_id in ids:
        for rel in files or list(INSTRUCTION_FILES):
            path = workspace_root / rel
            if not path.exists():
                continue
            text = path.read_text(encoding="utf-8")
            new_text, count = _block_regex(prompt_id).subn("", text)
            if count:
                path.write_text(re.sub(r"\n{3,}", "\n\n", new_text), encoding="utf-8")
            report.append({"id": prompt_id, "file": rel, "status": "removido" if count else "ausente"})
    return report
